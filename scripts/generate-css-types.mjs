/**
 * Generate a TypeScript declaration for every CSS Module.
 *
 * `vite/client` types `*.module.css` as a string index signature, so a class
 * lookup widens to `string | undefined` under `noUncheckedIndexedAccess` —
 * and TypeScript forbids `undefined` as a computed property name, which is
 * what the `clsx(base, { [styles.modifier]: condition })` form needs.
 *
 * A declaration next to the CSS file wins over the wildcard and gives each
 * class a literal type, so the computed-key form works and a typo in a class
 * name becomes a compile error.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, 'src');

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });

const extractClassNames = (css) => {
  const cleaned = css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/url\([^)]*\)/g, '');

  const names = new Set();
  for (const match of cleaned.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) {
    names.add(match[1]);
  }

  return [...names].sort();
};

const render = (classNames) => {
  const properties = classNames.map((name) => {
    const key = /^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`;
    return `  readonly ${key}: '${name}';`;
  });

  return [
    '// Generated by `npm run css-types` - do not edit by hand.',
    'declare const classes: {',
    ...properties,
    '};',
    '',
    'export default classes;',
    '',
  ].join('\n');
};

const cssFiles = walk(SRC).filter((file) => file.endsWith('.module.css'));

// Drop declarations whose CSS Module is gone. Computed before writing, so a
// declaration that was just generated is never mistaken for a stale one.
const cssSet = new Set(cssFiles);
const stale = walk(SRC).filter(
  (file) =>
    file.endsWith('.module.css.d.ts') &&
    !cssSet.has(file.replace(/\.d\.ts$/, '')),
);

for (const file of stale) {
  fs.rmSync(file);
  console.log(`removed ${path.relative(ROOT, file)}`);
}

let written = 0;
let unchanged = 0;

for (const cssFile of cssFiles) {
  const declarationFile = `${cssFile}.d.ts`;
  const content = render(extractClassNames(fs.readFileSync(cssFile, 'utf8')));

  if (fs.existsSync(declarationFile)) {
    if (fs.readFileSync(declarationFile, 'utf8') === content) {
      unchanged += 1;
      continue;
    }
  }

  fs.writeFileSync(declarationFile, content);
  written += 1;
  console.log(`updated ${path.relative(ROOT, declarationFile)}`);
}

console.log(
  `\n${written} written, ${unchanged} unchanged, ${stale.length} removed`,
);
